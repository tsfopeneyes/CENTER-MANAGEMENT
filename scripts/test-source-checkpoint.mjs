import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
import {createCheckpoint,verifyCheckpoint,rehearseCheckpoint} from './source-checkpoint.mjs';
const root=await mkdtemp(path.resolve('scratch/source-checkpoint-test-'));
for(const dir of ['src','public','scripts','docs','supabase','backups'])await mkdir(path.join(root,dir));
await writeFile(path.join(root,'src','fixture.js'),'export const value="복구";');
await writeFile(path.join(root,'.env'),'secret fixture excluded');
await writeFile(path.join(root,'package.json'),'{}');
const checkpoint=path.join(root,'backups','fixture');
await createCheckpoint(root,checkpoint);const verified=await verifyCheckpoint(checkpoint);
assert.equal(verified.files.length,2);assert.ok(!verified.files.some(f=>f.path.includes('.env')));
const restored=path.join(root,'restored');await rehearseCheckpoint(checkpoint,restored);
assert.equal(await readFile(path.join(restored,'src','fixture.js'),'utf8'),'export const value="복구";');
await assert.rejects(rehearseCheckpoint(checkpoint,restored),/EEXIST/);
await assert.rejects(createCheckpoint(root,checkpoint),/EEXIST/);
await writeFile(path.join(checkpoint,'src','fixture.js'),'tampered');
await assert.rejects(verifyCheckpoint(checkpoint),/integrity failure/);
await assert.rejects(createCheckpoint(root,path.join(root,'outside-backups')),/inside workspace backups/);
console.log('PASS source checkpoints: exact restore, secrets excluded, existing checkpoint/restore not overwritten, tampering detected');
