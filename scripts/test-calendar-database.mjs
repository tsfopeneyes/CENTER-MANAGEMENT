// Runs against an isolated in-memory PostgreSQL engine. No production connection.
// Test dependency: @electric-sql/pglite (available in the local verification environment).
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
try {
    await db.exec(`
        CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
        CREATE SCHEMA auth;
        CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
        CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql AS $$ SELECT current_setting('request.jwt.claim.role', true) $$;
        GRANT USAGE ON SCHEMA auth TO anon, authenticated, service_role;
        CREATE TABLE public.users (id uuid PRIMARY KEY, name text, role text, user_group text, auth_user_id uuid UNIQUE);
        INSERT INTO users (id,name,role,user_group,auth_user_id) VALUES
            ('00000000-0000-0000-0000-000000000001','Jin','admin','관리자','00000000-0000-0000-0000-000000000003'),
            ('00000000-0000-0000-0000-000000000002','학생','user','학생',null);
        CREATE TABLE public.notices (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, category text, title text, is_recruiting boolean, recruitment_deadline timestamptz, program_date timestamptz, program_end_date date, is_challenge boolean, program_status text, guest_properties jsonb);
        CREATE TABLE public.notice_responses (notice_id bigint REFERENCES public.notices(id), user_id uuid, status text, is_attended boolean, PRIMARY KEY(notice_id,user_id));
        CREATE TABLE public.logs (id int, content text);
        INSERT INTO logs VALUES (1,'원본 출석 기록');
        INSERT INTO notices (id,category,title,is_recruiting,program_date,recruitment_deadline) VALUES (1,'PROGRAM','기존 프로그램',true,now()-interval '30 days',now()-interval '31 days');
    `);
    const old = (await db.query('SELECT * FROM notices WHERE id=1')).rows[0];
    await db.exec(readFileSync(new URL('../supabase/migrations/20260831010000_calendar_recruitment_and_duty.sql', import.meta.url), 'utf8'));
    const after = (await db.query('SELECT * FROM notices WHERE id=1')).rows[0];
    for (const key of Object.keys(old)) assert.deepEqual(after[key], old[key]);
    assert.equal(after.recruitment_start_at, null);
    assert.equal((await db.query('SELECT * FROM logs')).rows[0].content, '원본 출석 기록');
    await db.exec(`
        INSERT INTO notices (id,category,title,is_recruiting,program_date,recruitment_start_at,recruitment_deadline,recruitment_details_ready) VALUES
            (2,'PROGRAM','모집 예정',true,now()+interval '5 days',now()+interval '1 day',now()+interval '2 days',true),
            (3,'PROGRAM','모집 중',true,now()+interval '5 days',now()-interval '1 day',now()+interval '2 days',true),
            (4,'PROGRAM','모집 종료',true,now()+interval '5 days',now()-interval '2 days',now()-interval '1 day',true),
            (5,'PROGRAM','정보 미작성',true,now()+interval '5 days',now()-interval '1 day',now()+interval '2 days',false);
        GRANT SELECT ON notices TO anon, authenticated;
        GRANT ALL ON notice_responses TO anon, authenticated;
        SELECT set_config('request.jwt.claim.role','anon',false);
        SET ROLE anon;
    `);
    const insert = id => db.exec(`INSERT INTO notice_responses VALUES (${id},'00000000-0000-0000-0000-000000000002','JOIN',false)`);
    await assert.rejects(insert(2), /모집 시작 전/);
    await insert(3);
    await assert.rejects(insert(4), /종료/);
    await assert.rejects(insert(5), /준비 중/);
    // Legacy enrollment behavior is unchanged, even when editing old records.
    await insert(1);
    await db.exec('RESET ROLE');
    await db.exec(`UPDATE notices SET recruitment_deadline=clock_timestamp()-interval '1 millisecond' WHERE id=3; SET ROLE anon;`);
    await db.exec('UPDATE notice_responses SET is_attended=true WHERE notice_id=3');
    await assert.rejects(db.exec('DELETE FROM notice_responses WHERE notice_id=3'), /종료/);
    await db.exec('RESET ROLE');
    assert.equal((await db.query('SELECT is_attended FROM notice_responses WHERE notice_id=3')).rows[0].is_attended, true);
    await assert.rejects(db.exec(`UPDATE notices SET recruitment_deadline=recruitment_start_at WHERE id=2`), /뒤여야/);
    await assert.rejects(db.exec(`UPDATE notices SET recruitment_start_at=null WHERE id=2`), /삭제할 수/);
    // Production still runs the old form until a separate hosting deployment.
    await db.exec(`INSERT INTO notices (id,category,is_recruiting,title) VALUES (6,'PROGRAM',true,'기존 화면 신규 등록')`);
    assert.equal((await db.query('SELECT recruitment_start_at FROM notices WHERE id=6')).rows[0].recruitment_start_at, null);
    await assert.rejects(db.exec(`INSERT INTO notices (id,category,is_recruiting,recruitment_start_at) VALUES (7,'PROGRAM',true,now())`), /뒤여야/);

    const seed = readFileSync(new URL('../supabase/migrations/20260831010100_seed_september_haifn_duty.sql', import.meta.url), 'utf8');
    await db.exec(seed);
    assert.equal(Number((await db.query('SELECT count(*) FROM center_duty_assignments')).rows[0].count), 22);
    assert.equal((await db.query("SELECT staff_id FROM center_duty_assignments WHERE duty_date='2026-09-04'")).rows[0].staff_id, '00000000-0000-0000-0000-000000000001');
    await db.exec(`UPDATE center_duty_assignments SET staff_name='수정 이름' WHERE duty_date='2026-09-01'`);
    await db.exec(seed);
    assert.equal((await db.query("SELECT staff_name FROM center_duty_assignments WHERE duty_date='2026-09-01'")).rows[0].staff_name, '수정 이름');
    await assert.rejects(db.exec(`INSERT INTO center_duty_assignments(center_code,duty_date,staff_name) VALUES ('HAIFN','2026-09-01','Duplicate')`), /duplicate/);
    await assert.rejects(db.exec(`INSERT INTO center_duty_assignments(center_code,duty_date,staff_name) VALUES ('ENOUGH_PLACE','2026-09-02','Wrong center')`), /check constraint/);
    await db.exec(`SET ROLE anon`);
    assert.equal(Number((await db.query('SELECT count(*) FROM center_duty_assignments')).rows[0].count), 22);
    await assert.rejects(db.exec(`INSERT INTO center_duty_assignments(center_code,duty_date,staff_name) VALUES ('HAIFN','2026-10-01','Unknown')`), /permission denied/);
    await db.exec(`RESET ROLE; SELECT set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000002',false); SELECT set_config('request.jwt.claim.role','authenticated',false); SET ROLE authenticated;`);
    await assert.rejects(db.exec(`INSERT INTO center_duty_assignments(center_code,duty_date,staff_name) VALUES ('HAIFN','2026-10-01','Student')`), /row-level security/);
    await db.exec(`RESET ROLE; SELECT set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000001',false); SET ROLE authenticated;`);
    await db.exec(`INSERT INTO center_duty_assignments(center_code,duty_date,staff_name) VALUES ('HAIFN','2026-10-01','Jin')`);
    await insert(4); // Verified administrator may correct historical enrollment.
    await db.exec('RESET ROLE');
    await db.exec(`SELECT set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000003',false); SET ROLE authenticated;`);
    assert.equal((await db.query('SELECT calendar_is_admin() AS allowed')).rows[0].allowed, true);
    await db.exec(`UPDATE center_duty_assignments SET staff_name='Jin' WHERE duty_date='2026-10-01'`);
    await db.exec('RESET ROLE');
    assert.equal((await db.query('SELECT * FROM logs')).rows.length, 1);
    console.log('PASS: additive migration, original rows/logs preserved, DB recruitment guards, attendance independence, legacy/admin behavior, duty RLS/uniqueness, non-destructive September seed.');
} finally { await db.close(); }
